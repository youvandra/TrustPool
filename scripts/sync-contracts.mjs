#!/usr/bin/env node
// Copies what the off-chain code needs from the Foundry project into @trustpool/core:
//   contracts/out/**         -> packages/core/src/contracts/abi.ts          (typed `as const` ABIs)
//   contracts/deployments/*  -> packages/core/src/contracts/deployments.ts  (addresses per chain id)
// Run `forge build` first. Both outputs are generated: never edit them by hand.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'contracts/out')
const deployments = join(root, 'contracts/deployments')
const target = join(root, 'packages/core/src/contracts')
const header = '// Generated by scripts/sync-contracts.mjs. Do not edit.\n\n'

const ARTIFACTS = [
  ['trustPoolAbi', 'TrustPool.sol/TrustPool.json'],
  ['swapAdapterAbi', 'ISwapAdapter.sol/ISwapAdapter.json'],
  ['erc20Abi', 'TrustPool.sol/IERC20Min.json'],
]

if (!existsSync(out)) {
  console.error('contracts/out is missing: run `forge build` in contracts/ first')
  process.exit(1)
}

let abi = header
for (const [name, file] of ARTIFACTS) {
  const { abi: items } = JSON.parse(readFileSync(join(out, file), 'utf8'))
  abi += `export const ${name} = ${JSON.stringify(items, null, 2)} as const\n\n`
}
writeFileSync(join(target, 'abi.ts'), abi.trimEnd() + '\n')

const found = existsSync(deployments)
  ? readdirSync(deployments)
      .filter((f) => /^\d+\.json$/.test(f))
      .map((f) => JSON.parse(readFileSync(join(deployments, f), 'utf8')))
      .sort((a, b) => a.chainId - b.chainId)
  : []
const entries = found.map((d) => `  ${d.chainId}: ${JSON.stringify(d, null, 2).replace(/\n/g, '\n  ')},`)
writeFileSync(
  join(target, 'deployments.ts'),
  header +
    "import type { Deployment } from './types'\n\n" +
    `export const DEPLOYMENTS: Record<number, Deployment> = {\n${entries.join('\n')}\n}\n`,
)
console.log(`abi.ts: ${ARTIFACTS.length} ABIs; deployments.ts: ${found.map((d) => d.chainId).join(', ') || 'none'}`)
